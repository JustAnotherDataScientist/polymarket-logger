#!/usr/bin/env bash
# deploy/setup.sh — First-time install on a fresh Ubuntu VM.
#
# Usage:
#   cd ~/polymarket-logger && bash deploy/setup.sh
#
# What it does:
#   1. Creates a Python venv + installs deps
#   2. Installs systemd service (pm-watcher)
#   3. Installs cron jobs (health check, backfill, log rotation)
#   4. Starts the service
#
# Prerequisites: Ubuntu 22.04+ with python3 and python3-venv
set -euo pipefail

G='\033[0;32m'; R='\033[0;31m'; Y='\033[1;33m'; W='\033[1m'; N='\033[0m'
ok()   { echo -e "${G}  ✓ $*${N}"; }
warn() { echo -e "${Y}  ⚠ $*${N}"; }
err()  { echo -e "${R}  ✗ $*${N}"; exit 1; }
step() { echo -e "\n${W}[$1] $2${N}"; }

PROJECT_DIR="$(cd "$(dirname "$0")/.." && pwd)"
VENV="$PROJECT_DIR/venv"
PYTHON="$VENV/bin/python"
LOGS="$PROJECT_DIR/logs"

echo -e "\n${W}═══════════════════════════════════════════${N}"
echo -e "${W}  PM·BN Watcher — Setup${N}"
echo -e "${W}═══════════════════════════════════════════${N}"
echo "  Project : $PROJECT_DIR"
echo "  Date    : $(date -u '+%Y-%m-%d %H:%M:%S UTC')"

# ── 1. System deps ──────────────────────────────────────────
step "1/5" "System packages"
sudo apt-get update -qq
sudo apt-get install -y -qq python3 python3-venv python3-full cron unzip
ok "python3, python3-venv, cron"

# ── 2. Python venv ──────────────────────────────────────────
step "2/5" "Python venv + dependencies"
if [ ! -d "$VENV" ]; then
    python3 -m venv "$VENV"
    ok "venv created"
else
    ok "venv already exists"
fi
"$VENV/bin/pip" install -q --upgrade pip
"$VENV/bin/pip" install -q -r "$PROJECT_DIR/requirements.txt"
ok "Dependencies installed"

# Verify imports
"$PYTHON" -c "
import pyarrow, pandas, websocket, requests
from event_store import EventStore
from ws_clients import PolymarketBookWS, MultiAssetBinanceTradeWS
from book_replay import BookReplayEngine
print('All imports OK')
" || err "Import check failed"
ok "Import check passed"

# ── 3. Directories ──────────────────────────────────────────
step "3/5" "Directories"
mkdir -p "$PROJECT_DIR/historical_data/live"
mkdir -p "$PROJECT_DIR/historical_data/events"
mkdir -p "$LOGS"
ok "historical_data/ + logs/"

# ── 4. Systemd service ─────────────────────────────────────
step "4/5" "Systemd service"
SERVICE_FILE="/etc/systemd/system/pm-watcher.service"
sudo tee "$SERVICE_FILE" > /dev/null <<EOF
[Unit]
Description=PM·BN Watcher — Polymarket + Binance live logger
After=network-online.target
Wants=network-online.target
StartLimitIntervalSec=60
StartLimitBurst=5

[Service]
Type=simple
User=$(whoami)
WorkingDirectory=$PROJECT_DIR
ExecStart=$PYTHON main.py
Restart=always
RestartSec=10
TimeoutStopSec=30
StandardOutput=journal
StandardError=journal
SyslogIdentifier=pm-watcher
Environment=PYTHONUNBUFFERED=1
Environment=TZ=UTC
LimitNOFILE=65536

[Install]
WantedBy=multi-user.target
EOF

sudo systemctl daemon-reload
sudo systemctl enable pm-watcher
sudo systemctl restart pm-watcher
sleep 4

if systemctl is-active --quiet pm-watcher; then
    ok "Service pm-watcher active"
else
    sudo journalctl -u pm-watcher -n 20 --no-pager
    err "Service failed to start"
fi

# ── 5. Crons ────────────────────────────────────────────────
step "5/5" "Cron jobs"
# Remove old pm-watcher crons, keep everything else
crontab -l 2>/dev/null | grep -v "pm-watcher\|health_check\|backfill_outcomes\|run_tests" > /tmp/crontab_clean || true

cat >> /tmp/crontab_clean <<EOF
# pm-watcher — auto-generated by setup.sh
*/15 * * * *  cd $PROJECT_DIR && $PYTHON tools/health_check.py >> $LOGS/health.log 2>&1
0 * * * *     cd $PROJECT_DIR && $PYTHON tools/backfill_outcomes.py >> $LOGS/backfill.log 2>&1
5 0 * * *     cd $PROJECT_DIR && $PYTHON tools/backfill_outcomes.py >> $LOGS/backfill_daily.log 2>&1
0 2 * * *     find $LOGS -name '*.log' -size +50M -exec truncate -s 0 {} \;
EOF

crontab /tmp/crontab_clean
rm -f /tmp/crontab_clean
ok "Crons installed"

# ── Summary ─────────────────────────────────────────────────
echo -e "\n${W}═══════════════════════════════════════════${N}"
echo -e "${G}${W}  ✅ Setup complete${N}"
echo -e "${W}═══════════════════════════════════════════${N}"
echo ""
echo "  Useful commands:"
echo "    sudo journalctl -u pm-watcher -f          # live logs"
echo "    sudo systemctl restart pm-watcher          # restart"
echo "    sudo systemctl stop pm-watcher             # stop"
echo "    cd $PROJECT_DIR && $PYTHON tools/health_check.py"
echo ""
echo "  Data directories:"
echo "    historical_data/events/   — raw events (for backtesting)"
echo "    historical_data/live/     — derived snapshots (for dashboard)"
echo ""
sudo journalctl -u pm-watcher -n 5 --no-pager
